// Builds the AI assistant's knowledge base from src/data/profile.js, so the chatbot can only
// ever say what the website itself says. Output: netlify/functions/assistant-knowledge.mjs
// Runs automatically as part of `yarn build`. Never fails the build: if it errors, the previously
// generated (committed) file is kept.
import fs from "node:fs";
import path from "node:path";
import { createServer } from "vite";

const OUT = path.resolve("netlify/functions/assistant-knowledge.mjs");

try {
  // Vite loads profile.js exactly as the app does (including its image imports).
  const server = await createServer({ server: { middlewareMode: true }, appType: "custom", logLevel: "silent" });
  const data = await server.ssrLoadModule("/src/data/profile.js");
  await server.close();

  const whatsapp = new URL(data.whatsappUrl("x"));
  whatsapp.search = "";

  const knowledge = {
    owner: { name: data.SITE.name, role: data.SITE.role, location: data.SITE.location },
    contact: {
      email: data.SITE.email,
      whatsapp: whatsapp.toString(),
      linkedin: data.LINKS.linkedin,
      github: data.LINKS.github,
      fiverr: data.LINKS.fiverr,
      contactForm: `${data.SITE.url}/#contact`,
      resume: `${data.SITE.url}${data.LINKS.resume}`,
      website: data.SITE.url,
    },
    facts: Object.fromEntries(data.FACTS),
    // These sentences mirror the About section of the site (src/components/About.jsx).
    about: [
      `${data.SITE.name} is a full-stack web developer from ${data.SITE.location}. He builds with JavaScript, React, Node.js, Express and MongoDB.`,
      "He likes problems real businesses have: a page that tells visitors what they need to know, a form that actually reaches the owner, a layout that works on a phone.",
      "He is early in his career and still studying, so he keeps projects focused, explains decisions in plain language, and says early if something is outside what he can deliver well.",
      "The projects shown on the site are his own projects, not paid client work.",
    ],
    services: data.SERVICES.map((s) => ({ title: s.title, description: s.text, includes: s.points })),
    projects: data.PROJECTS.map((p) => ({
      title: p.title, category: p.category, status: p.status, goal: p.goal, whatItDoes: p.built,
      hisPart: p.contribution, builtWith: p.tech, liveSite: p.live, sourceCode: p.repo,
    })),
    process: data.PROCESS.map((s) => ({ step: s.step, description: s.text })),
  };

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(
    OUT,
    `// AUTO-GENERATED by scripts/generate-assistant-knowledge.mjs from src/data/profile.js. Do not edit by hand.\nexport default ${JSON.stringify(knowledge, null, 2)};\n`,
  );
  console.log(`assistant knowledge: ${knowledge.projects.length} projects, ${knowledge.services.length} services -> ${path.relative(process.cwd(), OUT)}`);
} catch (err) {
  console.warn("assistant knowledge: generation failed, keeping the existing file.", err?.message ?? err);
}
